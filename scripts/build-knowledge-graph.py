import json
N=[];E=[]
def n(id,type,label,desc,path=None,**kw):
    d={"id":id,"type":type,"label":label,"description":desc}
    if path:d["path"]=path
    d.update(kw);N.append(d)
def e(s,rel,t,note=None):
    d={"source":s,"relation":rel,"target":t}
    if note:d["note"]=note
    E.append(d)

