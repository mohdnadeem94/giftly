# Decisions & gotchas
dec=[("dec.cents","Store money as integer cents."),
("dec.dbpush","Use prisma db push, no migrations (hackathon speed)."),
("dec.proof-in-db","Receipt images stored as Bytes in Postgres because Render disk isn't persistent."),
("dec.llm-fallback","LLM model fallback list after gemini-2.5-flash 404s and gemini-3.8-flash 503s."),
("dec.mui","MUI chosen over shadcn for UI."),
("gotcha.chip-icon","MUI Chip `icon` rendered from a server component causes a hydration mismatch; use a Box badge."),
("gotcha.aggrid-callbacks","Inline AG Grid callbacks (isExternalFilterPresent etc.) cause 'Maximum update depth exceeded'; wrap in useCallback."),
("gotcha.sx-important","`!important` in sx color tokens doesn't work; use explicit hex on .Mui-selected."),
("gotcha.charts-ssr","Charts render only after mount (useMounted) to avoid SSR mismatch.")]
for id,d in dec: n(id,"decision" if id.startswith("dec") else "gotcha",id.split('.',1)[1],d)

